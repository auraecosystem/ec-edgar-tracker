import gzip
import io
import os
import requests
import pandas as pd
from datetime import datetime

# Mandatory SEC Header Configuration
HEADERS = {
    'User-Agent': 'YourAutomationBot/1.0 admin-contact@example.com',
    'Accept-Encoding': 'gzip, deflate'
}

def fetch_daily_index_dataframe():
    """
    Downloads and parses the daily SEC index map.
    Uses the compressed (.gz) version to save automated runner bandwidth.
    """
    # Dynamically fetch yesterday or today's market log depending on running hour
    # Format sample: master.20261102.idx.gz
    date_str = datetime.today().strftime('%Y%m%d')
    url = f"https://sec.gov.{date_str}.idx.gz"
    
    print(f"Connecting to SEC Index Repository: {url}")
    response = requests.get(url, headers=HEADERS)
    
    if response.status_code == 404:
        print("Filing map not released yet for today. Skipping cycle.")
        return None
    elif response.status_code != 200:
        print(f"Connection rejected by SEC. Status Code: {response.status_code}")
        return None

    # Decompress binary stream directly in system memory
    with gzip.open(io.BytesIO(response.content), 'rt', encoding='latin-1') as f:
        content = f.read()

    # Split rows and locate the tabular data matrix boundaries
    lines = content.split('\n')
    data_start_idx = 0
    for idx, line in enumerate(lines):
        if "CIK|Company Name|Form Type|Date Filed|Filename" in line:
            data_start_idx = idx + 2  # Step past the header and dividing line
            break

    if data_start_idx == 0:
        print("Unexpected SEC .idx format schema detected.")
        return None

    # Parse rows cleanly into structured elements
    raw_records = [line.split('|') for line in lines[data_start_idx:] if '|' in line]
    
    columns = ["CIK", "Company Name", "Form Type", "Date Filed", "Filename"]
    df = pd.DataFrame(raw_records, columns=columns)
    return df

